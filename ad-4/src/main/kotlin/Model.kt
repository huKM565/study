package ru.hukm

class Trip(
    val number: Int,
    val route: String,
    val departure: String,
    val bus: String,
    val seats: Int,
    val driver: String,
    val price: Int,
) {
    override fun toString() = buildString {
        appendLine("  № рейса:      $number")
        appendLine("  Маршрут:      $route")
        appendLine("  Отправление:  $departure")
        appendLine("  Автобус:      $bus")
        appendLine("  Мест:         $seats")
        appendLine("  Водитель:     $driver")
        append("  Цена билета:  $price руб.")
    }
}

